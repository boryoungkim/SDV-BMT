#!/usr/bin/env python3
"""Write the experiment configurations of CenterPoint-Pillars (pillar02) on the GPU reference accelerator (tool;
stdlib only).

Same structure as the DeepLab family (tools/deeplab_family/make_experiments.py).  The replay rate of the baseline runs
is the tool's only parameter: it goes into ``replay.rate_hz`` and the frame-period deadline follows it
(``period_ns = floor(10**9 / rate_hz)``).  The rate itself is chosen by the DeepLab rule from the mini golden capture
(``tools/deeplab_family/choose_rate.py``) and is used for the full val run as well.

    python3 tools/centerpoint/make_experiments.py [--rate-hz R] [--check]

Files in configs/experiments/:
  centerpoint-pillar02-mini-algo-probe.yaml  algorithm policy "heuristic", closed loop (asap), the 162 mini val samples:
                                             the realized table must equal the pinned one (tools/centerpoint/pin_table.py)
  centerpoint-pillar02-mini-capture.yaml     pinned table, asap, the 162 samples, no output reference: the golden capture
  centerpoint-pillar02-mini-baseline.yaml    pinned table, fixed rate, deadline = frame period, output reference = the
                                             golden; written only with --rate-hz and once the golden exists
  centerpoint-pillar02-val-series.yaml       the full nuScenes val (6019 samples) as a run series (at most 1000 samples
                                             per part, scenes never split), same rate and deadline, no output
                                             reference; written only with --rate-hz and once configs/inputs/
                                             nuscenes-val.yaml exists
"""

from __future__ import annotations

import argparse
import hashlib
import math
from fractions import Fraction
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONFIGS = REPO / "configs"
NS_PER_S = 1_000_000_000
MINI = "nuscenes-mini-val4"
VAL = "nuscenes-val"
VAL_TEXT = "the full nuScenes val (150 official val scenes, 6019 samples)"
SERIES = "series: {max_items_per_run: 1000, boundary: scene}\n"
WORKLOAD = "centerpoint-pillar02-nus-v1"
PINNED = "nvidia-rtx-pro-6000-gpu0-cudnn-centerpoint-pillar02"
HEURISTIC = "nvidia-rtx-pro-6000-gpu0-cudnn-heuristic"
NAME = "CenterPoint-Pillars (pillar02)"
HARNESS_CPUS = ", ".join(str(c) for c in [*range(0, 16), *range(32, 48)])  # NUMA node 0, as the YOLOX/DeepLab runs
GENERATED = "# GENERATED by tools/centerpoint/make_experiments.py"
SCOPE = "# CenterPoint part (ACTUAL, reference_accelerator_validation; GPU 0; not an NPU result"
MINI_TEXT = "the 162 nuScenes mini val samples (4 official val scenes)"
REQUEST_TIMEOUT_NS = 1_000_000_000
RUN = f"""run:
  max_inflight: 1
  queue_capacity: 0
  on_full: drop_new
  request_timeout_ns: {REQUEST_TIMEOUT_NS:_}
  drain_ns: {REQUEST_TIMEOUT_NS:_}
  output_capture: task_output_all
  on_request_error: continue
"""


def frame_period_ns(rate_hz: float) -> int:
    return math.floor(Fraction(NS_PER_S) / Fraction(repr(float(rate_hz))))


def rate_text(rate_hz: float) -> str:
    return str(int(rate_hz)) if float(rate_hz).is_integer() else repr(float(rate_hz))


def golden_name(input_id: str) -> str:
    return f"{input_id}.{WORKLOAD}.gpu-capture.golden.jsonl"


def _plan(header: str, experiment_id: str, input_id: str, dut: str, replay: str, evaluation: str,
          preconditions: int, series: str = "") -> str:
    return (f"{header}\nschema_version: 1\nexperiment_id: {experiment_id}\nexecution_kind: actual\nseed: 0\n"
            f"repetitions: 1\ninput: ../inputs/{input_id}.yaml\nworkload: ../workloads/{WORKLOAD}.yaml\n"
            f"dut: ../duts/{dut}.yaml\nstress: {{spec: ../stress/fake-virtual-axis.yaml, level: none}}\n"
            f"replay: {replay}\n{RUN}{evaluation}realtime:\n  cpu_affinity: [{HARNESS_CPUS}]\n"
            f"  wait_policy: spin\n  precondition_requests: {preconditions}\n{series}")


def render(rate_hz: float | None) -> dict[Path, str]:
    asap = "{mode: asap, lead_ns: 2_000_000}"
    out: dict[Path, str] = {}
    exp = CONFIGS / "experiments"
    out[exp / "centerpoint-pillar02-mini-algo-probe.yaml"] = _plan(
        f"{GENERATED}; edit the tool, not this file.\n{SCOPE}). cuDNN algorithm probe:\n"
        f"# {NAME} on {MINI_TEXT} with algorithm policy \"heuristic\",\n# closed loop N=1 (asap). "
        "Purpose: the realized per-convolution table must equal the table the pinned DUT\n# configuration declares. "
        "Not part of the baseline distribution.",
        "centerpoint-pillar02-mini-algo-probe", MINI, HEURISTIC, asap, "", 4)
    out[exp / "centerpoint-pillar02-mini-capture.yaml"] = _plan(
        f"{GENERATED}; edit the tool, not this file.\n{SCOPE}). Golden capture:\n"
        f"# {NAME} (cuDNN plan, pinned algorithm table) on {MINI_TEXT},\n# closed loop N=1 (asap: no request is "
        "dropped whatever the service time), no output reference. Its encoded detections\n# become the output "
        "reference of the baseline runs (determinism / corruption diagnostic, not correctness), and its\n"
        "# DUT-service maximum feeds the replay-rate rule. Not part of the baseline distribution.",
        "centerpoint-pillar02-mini-capture", MINI, PINNED, asap, "", 32)
    golden = CONFIGS / "references" / golden_name(MINI)
    if rate_hz is not None and golden.is_file():
        rate, period = rate_text(rate_hz), frame_period_ns(rate_hz)
        out[exp / "centerpoint-pillar02-mini-baseline.yaml"] = _plan(
            f"{GENERATED} --rate-hz {rate}; rerun the tool to change\n# the replay rate (it is set nowhere else).\n"
            f"{SCOPE}, not a ranking). Baseline:\n"
            f"# {NAME} (cuDNN plan, pinned algorithm table) on {MINI_TEXT},\n# realtime harness pinned to NUMA node 0, "
            "nominal (no stress), N=1, queue 0, drop_new, 32 untimed precondition requests,\n"
            f"# fixed rate {rate} Hz (DeepLab replay-rate rule on the mini golden capture), deadline = frame period.\n"
            "# Run five times (one invocation each). Output reference = the golden capture (determinism/corruption\n"
            "# diagnostic only). Results of different models are compared side by side, not attributed.",
            "centerpoint-pillar02-mini-baseline", MINI, PINNED,
            f"{{mode: fixed_rate, rate_hz: {rate}, lead_ns: 2_000_000}}",
            f"evaluation:\n  deadline: {{policy: frame_period, period_ns: {period:_}}}\n  output_reference:\n"
            f"    kind: external_golden\n    path: ../references/{golden.name}\n"
            f"    sha256: {hashlib.sha256(golden.read_bytes()).hexdigest()}\n", 32)
    if rate_hz is not None and (CONFIGS / "inputs" / f"{VAL}.yaml").is_file():
        rate, period = rate_text(rate_hz), frame_period_ns(rate_hz)
        out[exp / "centerpoint-pillar02-val-series.yaml"] = _plan(
            f"{GENERATED} --rate-hz {rate}; rerun the tool to change\n# the replay rate (it is set nowhere else).\n"
            f"{SCOPE}, not a ranking). Full val as a run series:\n"
            f"# {NAME} (cuDNN plan, pinned algorithm table) on {VAL_TEXT},\n# run once as a run series: parts of at "
            "most 1000 samples in index (scene) order, a scene never split, each part an\n# ordinary run with its own "
            "32 untimed precondition requests (pinned-memory limit); `sdv-bmt evaluate SERIES_DIR` gives\n# one result. "
            f"Same harness, rate ({rate} Hz) and frame-period deadline as the mini baseline. No output reference\n"
            "# (the mini scenes are compared with the mini golden by an offline check).",
            "centerpoint-pillar02-val-series", VAL, PINNED,
            f"{{mode: fixed_rate, rate_hz: {rate}, lead_ns: 2_000_000}}",
            f"evaluation:\n  deadline: {{policy: frame_period, period_ns: {period:_}}}\n", 32, SERIES)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="Write the CenterPoint-Pillars experiment configurations.")
    ap.add_argument("--rate-hz", type=float, help="replay rate of the baseline runs")
    ap.add_argument("--check", action="store_true", help="compare with the files on disk instead of writing")
    a = ap.parse_args()
    if a.rate_hz is not None and not (math.isfinite(a.rate_hz) and a.rate_hz > 0):
        ap.error("--rate-hz must be a positive number")
    stale = []
    for path, text in sorted(render(a.rate_hz).items()):
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        if a.check:
            stale.append(str(path.relative_to(REPO)))
        else:
            path.write_text(text, encoding="utf-8")
            print("wrote", path.relative_to(REPO))
    if stale:
        print("differs from the tool output or is missing:", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
