#!/usr/bin/env python3
"""Write the experiment configurations of the v0.1.2 YOLOX family (Tiny, S, M, L, X) on the GPU reference
accelerator (tool; stdlib only).

The replay rate of the baseline runs is the tool's only parameter, so changing the rate of all five models is
one command: rerun the tool.  The rate goes into ``replay.rate_hz`` of every baseline file and the frame-period
deadline follows it (``period_ns = floor(10**9 / rate_hz)``, the replay schedule's own arithmetic).  No workload
or DUT configuration carries it.

    python3 tools/yolox_family/make_experiments.py --rate-hz 30 [--check]

Files in configs/experiments/, per model:
  yolox-<model>-algo-probe.yaml  cuDNN algorithm policy "heuristic", closed loop (asap), 1000 images: records the
                                 per-convolution algorithm table that the model's pinned DUT configuration declares
  yolox-<model>-capture.yaml     pinned table, asap, 1000 images, no output reference: the golden capture (not for
                                 YOLOX-S, whose v0.1.0 golden is its regression reference)
  yolox-<model>-baseline.yaml    pinned table, fixed rate, deadline = frame period, output reference = the model's
                                 golden; written once the golden exists (its SHA-256 is read from the file)
Probe and capture are preparation runs: in asap mode nothing is dropped, so the capture holds all 1000 outputs
whatever the model's service time.  Only the baselines use the replay rate.  --check writes nothing and exits 1
when a file differs from what would be written or is missing.
"""

from __future__ import annotations

import argparse
import hashlib
import math
from fractions import Fraction
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONFIGS = REPO / "configs"
NS_PER_S = 1_000_000_000
# model, name, input configuration, workload configuration, golden (configs/references/)
MODELS = (
    ("tiny", "YOLOX-Tiny", "coco-val2017-first1000-416", "yolox-tiny-coco-v1",
     "coco-val2017-first1000-416.yolox-tiny-coco-v1.gpu-capture.golden.jsonl"),
    ("s", "YOLOX-S", "coco-val2017-first1000", "yolox-s-coco-v1-quality",
     "coco-val2017-first1000.yolox-s-coco-v1.gpu-capture.golden.jsonl"),
    ("m", "YOLOX-M", "coco-val2017-first1000", "yolox-m-coco-v1",
     "coco-val2017-first1000.yolox-m-coco-v1.gpu-capture.golden.jsonl"),
    ("l", "YOLOX-L", "coco-val2017-first1000", "yolox-l-coco-v1",
     "coco-val2017-first1000.yolox-l-coco-v1.gpu-capture.golden.jsonl"),
    ("x", "YOLOX-X", "coco-val2017-first1000", "yolox-x-coco-v1",
     "coco-val2017-first1000.yolox-x-coco-v1.gpu-capture.golden.jsonl"),
)
CAPTURED_IN_V010 = {"s"}
HARNESS_CPUS = ", ".join(str(c) for c in [*range(0, 16), *range(32, 48)])  # NUMA node 0, as the v0.1.0 runs
GENERATED = "# GENERATED by tools/yolox_family/make_experiments.py"
SCOPE = "# v0.1.2 YOLOX family (ACTUAL, reference_accelerator_validation; GPU 0; not an NPU result"
RUN = """run:
  max_inflight: 1
  queue_capacity: 0
  on_full: drop_new
  request_timeout_ns: 1_000_000_000
  drain_ns: 1_000_000_000
  output_capture: task_output_all
  on_request_error: continue
"""


def frame_period_ns(rate_hz: float) -> int:
    return math.floor(Fraction(NS_PER_S) / Fraction(repr(float(rate_hz))))


def rate_text(rate_hz: float) -> str:
    return str(int(rate_hz)) if float(rate_hz).is_integer() else repr(float(rate_hz))


def _plan(header: str, experiment_id: str, input_id: str, workload: str, dut: str, replay: str, evaluation: str,
          preconditions: int) -> str:
    return (f"{header}\nschema_version: 1\nexperiment_id: {experiment_id}\nexecution_kind: actual\nseed: 0\n"
            f"repetitions: 1\ninput: ../inputs/{input_id}.yaml\nworkload: ../workloads/{workload}.yaml\n"
            f"dut: ../duts/{dut}.yaml\nstress: {{spec: ../stress/fake-virtual-axis.yaml, level: none}}\n"
            f"replay: {replay}\n{RUN}{evaluation}realtime:\n  cpu_affinity: [{HARNESS_CPUS}]\n"
            f"  wait_policy: spin\n  precondition_requests: {preconditions}\n")


def render(rate_hz: float) -> dict[Path, str]:
    """{path: text} of every file the tool owns for this replay rate."""
    rate, period = rate_text(rate_hz), frame_period_ns(rate_hz)
    asap = "{mode: asap, lead_ns: 2_000_000}"
    out: dict[Path, str] = {}
    for model, name, input_id, workload, golden in MODELS:
        pinned = f"nvidia-rtx-pro-6000-gpu0-cudnn-yolox-{model}"
        out[CONFIGS / "experiments" / f"yolox-{model}-algo-probe.yaml"] = _plan(
            f"{GENERATED}; edit the tool, not this file.\n{SCOPE}). cuDNN algorithm probe:\n"
            f"# {name} on the first 1000 COCO val2017 images with algorithm policy \"heuristic\", closed loop N=1 "
            "(asap).\n# Purpose: record the per-convolution (algorithm, math type) table in dut.prepare; the "
            "model's DUT\n# configuration then declares it with policy \"pinned\". Not part of the baseline "
            "distribution.",
            f"yolox-{model}-algo-probe", input_id, workload, "nvidia-rtx-pro-6000-gpu0-cudnn-heuristic", asap, "", 4)
        if model not in CAPTURED_IN_V010:
            out[CONFIGS / "experiments" / f"yolox-{model}-capture.yaml"] = _plan(
                f"{GENERATED}; edit the tool, not this file.\n{SCOPE}). Golden capture:\n"
                f"# {name} (cuDNN plan, pinned algorithm table) on the first 1000 COCO val2017 images, closed loop "
                "N=1\n# (asap: no request is dropped whatever the service time), no output reference. Its encoded "
                "task outputs\n# become the output reference of the model's baseline runs (a run-to-run determinism "
                "/ corruption\n# diagnostic, not correctness). Not part of the baseline distribution.",
                f"yolox-{model}-capture", input_id, workload, pinned, asap, "", 32)
        golden_path = CONFIGS / "references" / golden
        if not golden_path.is_file():
            continue
        reference = ("the v0.1.0 reference capture" if model in CAPTURED_IN_V010
                     else "the model's golden capture")
        out[CONFIGS / "experiments" / f"yolox-{model}-baseline.yaml"] = _plan(
            f"{GENERATED} --rate-hz {rate}; rerun the tool to change\n# the replay rate of all five YOLOX models "
            f"(it is set nowhere else).\n{SCOPE}, not a ranking). Baseline:\n"
            f"# {name} (cuDNN plan, pinned algorithm table) on the first 1000 COCO val2017 images, realtime "
            "harness pinned\n# to NUMA node 0, nominal (no stress), N=1, queue 0, drop_new, 32 untimed "
            f"precondition requests, fixed rate\n# {rate} Hz (the replay rate shared by the five models), deadline "
            f"= frame period.\n# Output reference = {reference} (determinism/corruption diagnostic only).\n"
            "# Results of different models are compared side by side, not attributed.",
            f"yolox-{model}-baseline", input_id, workload, pinned,
            f"{{mode: fixed_rate, rate_hz: {rate}, lead_ns: 2_000_000}}",
            f"evaluation:\n  deadline: {{policy: frame_period, period_ns: {period:_}}}\n  output_reference:\n"
            f"    kind: external_golden\n    path: ../references/{golden}\n"
            f"    sha256: {hashlib.sha256(golden_path.read_bytes()).hexdigest()}\n", 32)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="Write the v0.1.2 YOLOX family experiment configurations.")
    ap.add_argument("--rate-hz", type=float, required=True, help="replay rate of the five baseline runs")
    ap.add_argument("--check", action="store_true", help="compare with the files on disk instead of writing")
    a = ap.parse_args()
    if not (math.isfinite(a.rate_hz) and a.rate_hz > 0):
        ap.error("--rate-hz must be a positive number")
    stale = []
    for path, text in sorted(render(a.rate_hz).items()):
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        if a.check:
            stale.append(str(path.relative_to(REPO)))
        else:
            path.write_text(text, encoding="utf-8")
            print("wrote", path.relative_to(REPO))
    for model, _, _, _, golden in MODELS:
        if not (CONFIGS / "references" / golden).is_file():
            print(f"yolox-{model}-baseline.yaml not written: configs/references/{golden} does not exist yet")
    if stale:
        print("differs from the tool output or is missing:", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
