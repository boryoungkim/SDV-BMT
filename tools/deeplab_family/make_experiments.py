#!/usr/bin/env python3
"""Write the experiment configurations of the v0.1.2 DeepLabV3+ family (R-18, R-50, R-101) on the GPU reference
accelerator (tool; stdlib only).

The replay rate of the baseline runs is the tool's only parameter: it goes into ``replay.rate_hz`` of every baseline
file and the frame-period deadline follows it (``period_ns = floor(10**9 / rate_hz)``).  No workload or DUT
configuration carries it, and plan validation rejects a baseline whose deadline does not follow its rate.  The rate
itself is chosen by the rule of plan v03 section 4.5 from the golden captures (``choose_rate.py``).

    python3 tools/deeplab_family/make_experiments.py [--rate-hz R] [--check]

Files in configs/experiments/, per model:
  deeplabv3plus-<m>-algo-probe.yaml  algorithm policy "heuristic", closed loop (asap), the 500 val images: the realized
                                     table must equal the pinned one (tools/deeplab_family/pin_table.py)
  deeplabv3plus-<m>-capture.yaml     pinned table, asap, the 500 val images, no output reference: the golden capture
  deeplabv3plus-<m>-baseline.yaml    pinned table, fixed rate, deadline = frame period, output reference = the golden;
                                     written only with --rate-hz and once the golden exists
Without --rate-hz only the probe and capture files are written (or checked).
"""

from __future__ import annotations

import argparse
import hashlib
import math
from fractions import Fraction
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CONFIGS = REPO / "configs"
NS_PER_S = 1_000_000_000
INPUT_ID = "cityscapes-val500"
MODELS = (("r18", "DeepLabV3+ R-18"), ("r50", "DeepLabV3+ R-50"), ("r101", "DeepLabV3+ R-101"))
HARNESS_CPUS = ", ".join(str(c) for c in [*range(0, 16), *range(32, 48)])  # NUMA node 0, as the YOLOX runs
GENERATED = "# GENERATED by tools/deeplab_family/make_experiments.py"
SCOPE = "# v0.1.2 DeepLabV3+ family (ACTUAL, reference_accelerator_validation; GPU 0; not an NPU result"
REQUEST_TIMEOUT_NS = 1_000_000_000  # plan v03 4.5: raised to 2 s only if an asap capture exceeds 0.5 s
RUN = f"""run:
  max_inflight: 1
  queue_capacity: 0
  on_full: drop_new
  request_timeout_ns: {REQUEST_TIMEOUT_NS:_}
  drain_ns: {REQUEST_TIMEOUT_NS:_}
  output_capture: task_output_all
  on_request_error: continue
"""


def frame_period_ns(rate_hz: float) -> int:
    return math.floor(Fraction(NS_PER_S) / Fraction(repr(float(rate_hz))))


def rate_text(rate_hz: float) -> str:
    return str(int(rate_hz)) if float(rate_hz).is_integer() else repr(float(rate_hz))


def golden_name(model: str) -> str:
    return f"{INPUT_ID}.deeplabv3plus-{model}-cityscapes-v1.gpu-capture.golden.jsonl"


def _plan(header: str, experiment_id: str, workload: str, dut: str, replay: str, evaluation: str,
          preconditions: int) -> str:
    return (f"{header}\nschema_version: 1\nexperiment_id: {experiment_id}\nexecution_kind: actual\nseed: 0\n"
            f"repetitions: 1\ninput: ../inputs/{INPUT_ID}.yaml\nworkload: ../workloads/{workload}.yaml\n"
            f"dut: ../duts/{dut}.yaml\nstress: {{spec: ../stress/fake-virtual-axis.yaml, level: none}}\n"
            f"replay: {replay}\n{RUN}{evaluation}realtime:\n  cpu_affinity: [{HARNESS_CPUS}]\n"
            f"  wait_policy: spin\n  precondition_requests: {preconditions}\n")


def render(rate_hz: float | None) -> dict[Path, str]:
    asap = "{mode: asap, lead_ns: 2_000_000}"
    out: dict[Path, str] = {}
    for model, name in MODELS:
        workload = f"deeplabv3plus-{model}-cityscapes-v1"
        pinned = f"nvidia-rtx-pro-6000-gpu0-cudnn-deeplabv3plus-{model}"
        out[CONFIGS / "experiments" / f"deeplabv3plus-{model}-algo-probe.yaml"] = _plan(
            f"{GENERATED}; edit the tool, not this file.\n{SCOPE}). cuDNN algorithm probe:\n"
            f"# {name} on the 500 Cityscapes val images with algorithm policy \"heuristic\", closed loop N=1 (asap).\n"
            "# Purpose: the realized per-convolution table must equal the table the pinned DUT configuration declares.\n"
            "# Not part of the baseline distribution.",
            f"deeplabv3plus-{model}-algo-probe", workload, "nvidia-rtx-pro-6000-gpu0-cudnn-heuristic", asap, "", 4)
        out[CONFIGS / "experiments" / f"deeplabv3plus-{model}-capture.yaml"] = _plan(
            f"{GENERATED}; edit the tool, not this file.\n{SCOPE}). Golden capture:\n"
            f"# {name} (cuDNN plan, pinned algorithm table) on the 500 Cityscapes val images, closed loop N=1 (asap: no\n"
            "# request is dropped whatever the service time), no output reference. Its encoded label maps become the\n"
            "# output reference of the model's baseline runs (determinism / corruption diagnostic, not correctness), and\n"
            "# its DUT-service maximum feeds the replay-rate rule. Not part of the baseline distribution.",
            f"deeplabv3plus-{model}-capture", workload, pinned, asap, "", 32)
        golden = CONFIGS / "references" / golden_name(model)
        if rate_hz is None or not golden.is_file():
            continue
        rate, period = rate_text(rate_hz), frame_period_ns(rate_hz)
        out[CONFIGS / "experiments" / f"deeplabv3plus-{model}-baseline.yaml"] = _plan(
            f"{GENERATED} --rate-hz {rate}; rerun the tool to change\n# the replay rate of the three DeepLabV3+ "
            f"models (it is set nowhere else).\n{SCOPE}, not a ranking). Baseline:\n"
            f"# {name} (cuDNN plan, pinned algorithm table) on the 500 Cityscapes val images, realtime harness pinned to\n"
            "# NUMA node 0, nominal (no stress), N=1, queue 0, drop_new, 32 untimed precondition requests, fixed rate\n"
            f"# {rate} Hz (the replay rate shared by the three models, plan v03 rule), deadline = frame period.\n"
            "# Output reference = the model's golden capture (determinism/corruption diagnostic only).\n"
            "# Results of different models are compared side by side, not attributed.",
            f"deeplabv3plus-{model}-baseline", workload, pinned,
            f"{{mode: fixed_rate, rate_hz: {rate}, lead_ns: 2_000_000}}",
            f"evaluation:\n  deadline: {{policy: frame_period, period_ns: {period:_}}}\n  output_reference:\n"
            f"    kind: external_golden\n    path: ../references/{golden.name}\n"
            f"    sha256: {hashlib.sha256(golden.read_bytes()).hexdigest()}\n", 32)
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description="Write the v0.1.2 DeepLabV3+ family experiment configurations.")
    ap.add_argument("--rate-hz", type=float, help="replay rate of the three baseline runs")
    ap.add_argument("--check", action="store_true", help="compare with the files on disk instead of writing")
    a = ap.parse_args()
    if a.rate_hz is not None and not (math.isfinite(a.rate_hz) and a.rate_hz > 0):
        ap.error("--rate-hz must be a positive number")
    stale = []
    for path, text in sorted(render(a.rate_hz).items()):
        if path.is_file() and path.read_text(encoding="utf-8") == text:
            continue
        if a.check:
            stale.append(str(path.relative_to(REPO)))
        else:
            path.write_text(text, encoding="utf-8")
            print("wrote", path.relative_to(REPO))
    if stale:
        print("differs from the tool output or is missing:", ", ".join(stale))
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
